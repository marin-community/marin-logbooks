"""Generate INVOCATIONS.md from the byte-exact submit scripts under evidence/scratch."""
import glob, json, os, re, sys
NB = os.path.abspath(sys.argv[1])
os.chdir(os.path.join(NB, "evidence"))
def cell(x): return str(x).replace("|", "/")
rows = []
for f in sorted(glob.glob("scratch/margay-submit-*.py")):
    t = open(f).read()
    dirs = sorted(set(re.findall(r"P\s*/\s*'([^']+)'", t)) | set(re.findall(r"snowball-identity/path-b/([A-Za-z0-9_.\-]+)'", t)))
    dirs = [d for d in dirs if os.path.isdir("notes/path-b/" + d.split("/")[0])]
    ws = sorted(set(os.path.basename(w) for w in re.findall(r"C\s*=\s*Path\('([^']+)'\)", t)))
    pin = sorted(set(re.findall(r"PIN\s*=\s*'([0-9a-f]{40})'", t)))
    calls = sorted(set(re.findall(r"\b(?:m|mod|packet)?\.?((?:request|prepare)\([^()\n]{0,80}\))", t)))
    args = [(a + " " + re.sub(r"\s+", " ", r).strip(", ")).strip() for a, r in re.findall(r"add_argument\('(--?[a-z0-9-]+)'((?:[^()]|\([^()]*\))*)\)", t) if a != "--orders-sha256"]
    pri = sorted(set(p.lower() for p in re.findall(r"PRIORITY_BAND_([A-Z]+)", t)))
    name = os.path.basename(f)
    rows.append("| [`{}`]({}) | {} | {} | {} | {} | {} |".format(
        name[len("margay-submit-"):-3], f,
        "<br>".join(f"[`{d}`](notes/path-b/{d})".replace("](notes", "](evidence/notes") for d in dirs) or "inline",
        (f"`{pin[0][:12]}`" if pin else "see script") + (f" ({ws[0]})" if ws else ""),
        "<br>".join(f"`{cell(c)}`" for c in calls) or "inline `client.submit`",
        "<br>".join(f"`{cell(a)}`" for a in args) or "none",
        "/".join(pri) or "see packet"))
    rows[-1] = rows[-1].replace(f"]({f})", f"](evidence/{f})", 1)
head = f"""# Submit invocations

This table is generated by [`gen_invocations.py`](gen_invocations.py) (`python3 gen_invocations.py .`). It lists every job submission behind the Path B results. It has one row per submit script under `evidence/scratch/margay-submit-*.py`. These {len(rows)} scripts are the exact programs that submitted the jobs. They are kept byte for byte; `evidence/MANIFEST.json` has their hashes.

Columns:
- **Packet**: the sealed packet folder the script loads (`launch-plan.json`, `prepare_request.py`, review receipts). "inline" means the script builds the request itself.
- **Pin**: the Marin commit the script checks out and verifies (`git rev-parse HEAD`). The old worktree name is in brackets. All pins are parents of this branch; see [PINS.md](PINS.md).
- **Entry call**: the packet function the script calls. `request(...)` returns keyword arguments for `IrisClient.submit`. `prepare(label, run)` returns a batch that the packet's `submit(batch, client)` sends.
- **Arguments**: the command-line arguments, as the script's `argparse` defines them. The values used per job are in each packet's `actual-launch-*.json` receipt.
- **Priority**: the priority band the script asserts before it submits. Training roots ran at `interactive`. Evaluation priority changed over time: earlier evaluations ran at `interactive`, and later ones (A12, A13, the merges and the SWE100 top-up) at `production`.

## How to run one of these again

The scripts only work as written on the original machine. To run one elsewhere:

1. Check out its pin in a fresh worktree: `git worktree add ../w <pin>`.
2. Remap the absolute paths in the script and in the packet's receipts:
   - the worktree path (the name in brackets) → your worktree;
   - `/home/karan/Dropbox/marin-notes/snowball-identity/` → `evidence/notes/`;
   - `/mnt/storage/karan-scratch/` → `evidence/scratch/`.
   Each packet re-checks the SHA256 of every file it lists, so a wrong remap fails loudly.
3. Remove two guards that read files not published here:
   - `--orders-sha256` and its check of an internal orders file;
   - `load_dotenv('/home/karan/oa/marin/.env')`. Export `CW_KEY_ID` and `CW_KEY_SECRET` in the environment instead (and `HF_TOKEN` for Hugging Face uploads). Never load a whole `.env` file.
4. Point every output prefix (`s3://marin-rno2a/...`) at storage you control. The script refuses to run if its output prefix already exists.

**What was checked.** These scripts are archival records of what ran, not portable or tested runners. Only the two A13 training packets were composed offline after the runs (see REPRODUCE.md §3). No other script has been re-executed or validated since it ran.

| Script | Packet | Pin | Entry call | Arguments | Priority |
|---|---|---|---|---|---|
"""
open(os.path.join(NB, "INVOCATIONS.md"), "w").write(head + "\n".join(rows) + "\n")
print(len(rows))
